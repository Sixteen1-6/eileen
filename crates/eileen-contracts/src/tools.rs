//! MCP tools (BUILD.md section 3.3.9): the tool specs every connector serves, the toolsets, and
//! one module of argument structs per toolset.
//!
//! Provisional: WP2 pins this module in its first pull request (BUILD.md section 3.3).
//!
//! One MCP server name, `eileen`, served by `eileen-shim` and forwarded to the core's
//! dispatcher, so Claude sees `mcp__eileen__<tool>`. The argument structs generate the input
//! schemas the dispatcher serves ([`input_schemas`]); path fields carry the `x-eileen-path`
//! extension and match-only fields `x-eileen-match`. Fields a model may leave out (lists,
//! flags) default when missing.

