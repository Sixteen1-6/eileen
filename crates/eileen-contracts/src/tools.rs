pub const MATCH_EXTENSION: &str = "x-eileen-match";

/// One tool, as a connector's manifest declares it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct ToolSpec {
    /// Its name.
    pub name: ToolName,
    /// The connector that serves it.
    pub connector: ConnectorId,
    /// Its home toolset.
    pub toolset: Toolset,
    /// At most 600 characters, written for the model.
    pub description: String,
    /// One entry per op; one entry named `""` for tools without ops.
    pub ops: Vec<OpSpec>,
    /// `op` or `action`: the argument field whose enum variant is the op; `None` for tools
    /// without ops.
    pub selector: Option<String>,
    /// How long a call may take.
    pub timeout_ms: u32,
    /// Generated by schemars from the argument struct.
    pub input_schema: Value,
    /// BLAKE3 of `input_schema` and every op's `output_schema`; recipes record it.
    pub schema_hash: String,
    /// The route this tool represents.
    pub rung: Rung,
}

/// One op of a tool. `op` is the selector variant's `snake_case` tag (`timeline_info`,
/// `status`, `snap`), the same tag recipes, checks and trajectories hold.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[expect(clippy::struct_excessive_bools, reason = "independent properties of one op")]
pub struct OpSpec {
    /// The op's tag.
    pub op: String,
    /// Its tier.
    pub tier: TierRule,
    /// Usable as a recipe check (tier 0 only).
    pub read_only: bool,
    /// A recipe may retry it once.
    pub idempotent: bool,
    /// It only writes new files into the job's temp folder, so an extra call does not break
    /// shadow agreement (section 2.10 item 7).
    pub artifact_only: bool,
    /// It takes the input lock and a lease.
    pub needs_foreground: bool,
    /// Show the target or crop and ask before running (hard-to-undo edits).
    pub preview_before: bool,
    /// How the journal reverses it; the op's output carries its inputs.
    pub inverse: Option<String>,
    /// From the op's result struct; required for any op a recipe may call or point into.
    pub output_schema: Option<Value>,
    /// The class of everything the op returns, its verification hint included.
    pub observes: ObservesRule,
}

/// How an op's tier is decided.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum TierRule {
    /// Always this tier.
    Fixed(Tier),
    /// The server computes it per call.
    ByArgs,
}

/// The observed-source class of what an op returns (section 2.12's observed-read table).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ObservesRule {
    /// Nothing from outside Eileen.
    None,
    /// Always this source.
    Fixed(ObservedSource),
    /// By the window or app it targets.
    ByTarget,
    /// By its arguments.
    ByArgs,
    /// By the jobs it lists.
    ByJobs,
}

/// The arguments of a tool that takes none: an empty object.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[expect(
    clippy::empty_structs_with_brackets,
    reason = "MCP tool inputs are JSON objects; a unit struct would serialize as null"
)]
pub struct NoArgs {}

/// One tool's input schema, as the dispatcher serves it.
#[derive(Debug, Clone, PartialEq)]
pub struct ToolInput {
    /// The contracts module that holds its argument struct.
    pub module: &'static str,
    /// The schema, self-contained (its definitions under `$defs`).
    pub schema: Value,
}

/// Every tool's input schema, by tool name.
#[must_use]
pub fn input_schemas() -> BTreeMap<&'static str, ToolInput> {
    let mut out = BTreeMap::new();
    brain::inputs(&mut out);
    worker::inputs(&mut out);
    desktop::inputs(&mut out);
    apps::inputs(&mut out);
    learn::inputs(&mut out);
    session::inputs(&mut out);
    dev::inputs(&mut out);
    out
}

/// Adds the input schema of the argument struct `T` for one tool.
fn input<T: JsonSchema>(
    out: &mut BTreeMap<&'static str, ToolInput>,
    module: &'static str,
    name: &'static str,
) {
    let schema = crate::schema::settings().into_generator().into_root_schema_for::<T>();
    out.insert(name, ToolInput { module, schema: schema.to_value() });
}

/// The tools of a toolset (the table of section 3.3.9). `approve` is in the worker toolset
/// only if WP3's contract test picks the permission-prompt-tool route, and `session_skills` in
/// the session toolset only with `claude_plugin.share_skills` on; the dispatcher applies both
/// conditions.
#[must_use]
pub const fn toolset_members(toolset: Toolset) -> &'static [&'static str] {
    match toolset {
        Toolset::Brain => BRAIN_TOOLS,
        Toolset::Act => ACT_TOOLS,
        Toolset::Worker => WORKER_TOOLS,
        Toolset::Desktop => DESKTOP_TOOLS,
        Toolset::Apps => APPS_TOOLS,
        Toolset::Learn => LEARN_TOOLS,
        Toolset::Session => SESSION_TOOLS,
        Toolset::Dev => DEV_TOOLS,
    }
}

